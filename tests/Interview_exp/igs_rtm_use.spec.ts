// why we use rtm

//"Requirement traceability is the process of mapping each requirement to its corresponding test cases, 
// automation scripts, execution results and defects. In my project, when a user story and acceptance criteria 
// are provided, I identify the functional scenarios and create or map test cases to the requirement. For
//  automation, I ensure the automated test can be traced back to the corresponding requirement or test case, 
// usually through our test-management or work-item system. During regression and release validation, this
//  helps me identify missing coverage, understand the impact of requirement changes, and provide evidence 
// that the requirements have been validated. If an automated test fails, I also link the resulting defect
//  back to the requirement and test case."

/*

Requirement
     ↓
"What should the system do?"
     ↓
Test Case
     ↓
"How will I verify it?"
     ↓
Automation
     ↓
"Can I execute it automatically?"
     ↓
Result
     ↓
"Did it pass?"
     ↓
Defect
     ↓
"If it failed, why?"

*/